import type { Artist, GenreId } from '../types.js';

/**
 * Curated local catalogue. This is the MVP's source of truth so the app works
 * with no network access; a remote provider can enrich it later.
 * Facts here (origins, years, albums, songs) are kept deliberately simple.
 */

function artist(
  id: string,
  name: string,
  genres: GenreId[],
  origin: string,
  since: number,
  blurb: string,
  album: [string, number],
  songs: string[],
  relatedArtists: string[],
  extra: { influences?: string[]; aliases?: string[] } = {},
): Artist {
  return {
    id,
    name,
    genres,
    origin,
    since,
    blurb,
    album: { title: album[0], year: album[1] },
    songs: songs.map((title) => ({ title })),
    relatedArtists,
    influences: extra.influences,
    aliases: extra.aliases,
  };
}

